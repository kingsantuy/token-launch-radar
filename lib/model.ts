// The token radar's model, version radar-2: one snapshot of the protocol universe in, one ranked
// board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. An early
// row passes the same exclusion the watchlist rule applies: pre-token, not an exchange, not a
// bridge-family, liquid-staking or restaked product, not a versioned pool, and its name carries no
// whole word "wrapped", "staked" or "staking" and does not begin with an exchange's name. A
// protocol is pre-token when its index entry records no token (no market cap, no CoinGecko id, no
// symbol); the snapshot's live-token protocols are kept apart and shown as the market's own values,
// never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures:
//
//   multiple   = the category's median mcap/TVL over token-bearing comps in the same category
//                (market cap above zero, at least 3 comps), clamped to [0.05, 1.00]; any other
//                category uses the whole-comp median, 0.2138
//   base       = tvl_usd x multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.5
//   breadth    = 1 + 0.02 x min(max(chains - 1, 0), 10)
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   implied    = max(1, round(base x growthMult x breadth x maturity))
//
// The category multiples are medians, not means, so one outlier cannot set them: Basis Trading
// 0.6544 (n=7), CDP 0.1687 (n=3), Dexs 0.3424 (n=11), Indexes 0.1477 (n=3), Lending 0.1324
// (n=15), RWA 0.2748 (n=9), Yield 0.1914 (n=9), Yield Aggregator 0.1510 (n=4); every other
// category uses the overall median 0.2138 (n=128). Comps with a zero or negative market cap are
// excluded from the medians: a zero market cap is a listing artefact, not a valuation. The
// multiples are thin for the biggest watchlist names — most comps are far smaller than the
// protocols they price, and 22 of the 40 watchlist rows use the overall median — so the board
// prints every row's multiple beside its implied value, and the dashboard names the limitation.
// No protocol name is ever special-cased: the same function scores every row.

